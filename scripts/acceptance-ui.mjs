// Run against scripts/demo.mjs only. It mutates that server's synthetic fixtures.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const url = new URL(process.argv[2]);
if (url.hostname !== '127.0.0.1') throw new Error('Only the local synthetic demo server is accepted');
const output = path.resolve(process.argv[3] || 'work/ui-acceptance');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
const checks = [], errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1100 }, locale: 'en-US' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url.href);
  await page.getByText(/Synthetic data/).first().waitFor();
  const frame = page.frameLocator('#app');
  await frame.locator('.activity-ranking li').first().waitFor();
  assert.equal(await frame.locator('.manager-body').isVisible(), false);
  await frame.getByRole('button', { name: 'Manage', exact: true }).click();
  assert.equal(await frame.locator('#activity-panel').isVisible(), false);
  const search = frame.getByLabel('Search name, description or path');
  await search.fill('chart-demo');
  await frame.getByLabel('Source', { exact: true }).selectOption({ label: 'User skill' });
  assert.equal(await frame.locator('.manager-list li').count(), 1);
  await frame.getByText('Source and notes', { exact: true }).click();
  const note = frame.getByLabel('Local note', { exact: true });
  await note.fill('Retain this synthetic example for acceptance.');
  await frame.getByLabel('Mark to retain').check();
  await frame.getByRole('button', { name: 'Save note', exact: true }).click();
  await frame.locator('.manager-feedback').filter({ hasText: 'Done.' }).waitFor();
  await frame.getByText('Source and notes', { exact: true }).click();
  assert.equal(await note.inputValue(), 'Retain this synthetic example for acceptance.');
  assert.equal(await frame.getByLabel('Mark to retain').isChecked(), true);
  checks.push('separate management view, search and persisted note');
  await note.fill('Unsaved local draft');
  await page.evaluate(async () => {
    const call = async (name, args = {}) => (await fetch('/tool', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name, arguments: args }) })).json();
    const skill = (await call('open_skill_manager')).structuredContent.skills.find(s => s.name === 'chart-demo' && s.source === '用户技能');
    const saved = await call('save_skill_note', { id: skill.id, fingerprint: skill.fingerprint, expectedRevision: skill.annotation.revision, note: 'Concurrent synthetic edit', retain: true });
    if (saved.isError) throw new Error('Could not set up competing note revision');
  });
  await frame.getByRole('button', { name: 'Save note', exact: true }).click();
  await frame.locator('.manager-feedback').filter({ hasText: 'Action not completed:' }).waitFor();
  await frame.getByText('Source and notes', { exact: true }).click();
  await frame.getByRole('button', { name: 'Discard draft and reload', exact: true }).click();
  await frame.locator('.manager-feedback').filter({ hasText: 'Done.' }).waitFor();
  await frame.getByText('Source and notes', { exact: true }).click();
  assert.equal(await note.inputValue(), 'Concurrent synthetic edit');
  await note.fill('Retain this synthetic example for acceptance.');
  await frame.getByRole('button', { name: 'Save note', exact: true }).click();
  await frame.locator('.manager-feedback').filter({ hasText: 'Done.' }).waitFor();
  await frame.getByText('Source and notes', { exact: true }).click();
  checks.push('stale note conflicts do not overwrite; explicit draft discard reloads the current revision');
  await frame.getByRole('button', { name: 'Preview archive', exact: true }).click();
  await frame.getByRole('button', { name: 'Confirm archive', exact: true }).waitFor();
  assert.equal(await frame.locator('.manager-list li').count(), 1);
  await frame.getByRole('button', { name: 'Cancel', exact: true }).click();
  await frame.locator('.manager-feedback').filter({ hasText: 'Done.' }).waitFor();
  assert.equal(await frame.locator('.manager-plan').count(), 0);
  assert.equal(await frame.locator('.manager-list li').count(), 1);
  checks.push('preview and cancellation do not move files');
  await frame.getByText('Source and notes', { exact: true }).click();
  await frame.getByRole('button', { name: 'Preview archive', exact: true }).click();
  await frame.getByRole('button', { name: 'Confirm archive', exact: true }).click();
  await frame.getByRole('button', { name: 'Preview restore', exact: true }).waitFor();
  assert.equal(await frame.locator('.manager-list li').count(), 0);
  await frame.getByRole('button', { name: 'Preview restore', exact: true }).click();
  await frame.getByRole('button', { name: 'Confirm restore', exact: true }).click();
  await frame.locator('.manager-list li').waitFor();
  await frame.getByText('Source and notes', { exact: true }).click();
  assert.equal(await note.inputValue(), 'Retain this synthetic example for acceptance.');
  checks.push('confirmed archive and restore move the synthetic skill and preserve its note');
  await page.screenshot({ path: path.join(output, 'management-en.png') });
  await page.getByRole('button', { name: 'Narrow panel', exact: true }).click();
  const overflow = await frame.locator('body').evaluate(element => element.scrollWidth > element.clientWidth);
  assert.equal(overflow, false);
  await page.screenshot({ path: path.join(output, 'management-narrow-en.png') });
  checks.push('management fits a 360px panel');
  await frame.getByRole('button', { name: 'Setup', exact: true }).click();
  await frame.getByRole('button', { name: 'Check recording status', exact: true }).click();
  await frame.getByText(/Latest received/).first().waitFor();
  await page.screenshot({ path: path.join(output, 'setup-en.png') });
  checks.push('read-only recording check shows received timestamps');
  await frame.getByRole('button', { name: 'Activity', exact: true }).click();
  assert.equal(await frame.locator('#activity-panel').isVisible(), true);
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, 'result.json'), JSON.stringify({ checks, errors, host: 'Browser AppBridge; native Codex UI not exercised', data: 'synthetic only' }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); }
