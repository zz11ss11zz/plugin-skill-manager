// Real browser checks against the local synthetic MCP Apps harness; never native-host acceptance.
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const url=new URL(process.argv[2]);
if(url.hostname!=='127.0.0.1')throw new Error('Only the local synthetic demo is accepted');
const output=path.resolve(process.argv[3]);await mkdir(output,{recursive:true});
const english=process.argv.includes('--en'),t=(zh,en)=>english?en:zh;
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
const errors=[],checks=[];
try{
  const page=await browser.newPage({viewport:{width:1100,height:1200},locale:english?'en-US':'zh-CN',colorScheme:'light'});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url.href);
  const f=page.frameLocator('#app');
  await f.locator('.activity-bar').last().waitFor();
  assert.equal(await f.locator('.manager-nav button').count(),2);
  assert.deepEqual(await f.locator('.manager-nav button').allTextContents(),[t('活动','Activity'),t('管理','Manage')]);
  assert.equal(await f.locator('.activity-bar').count(),30);
  const visibleText=await f.locator('body').innerText();
  if(english)assert.ok(!/[\u3400-\u9fff]/.test(visibleText), 'English preview has untranslated UI text');
  const bar=f.locator('.activity-bar').last();
  const label=await bar.getAttribute('aria-label'),date=label.slice(0,10);
  await bar.hover();
  assert.ok((await f.locator('.activity-tooltip').first().innerText()).includes(date));
  await bar.click();
  assert.equal(await f.locator('.activity-bar[aria-pressed=true]').count(),1);
  assert.equal(await f.locator('.calendar-cells [aria-pressed=true]').count(),1);
  assert.ok((await f.locator('.daily-heading').innerText()).includes(date));
  assert.ok(await f.locator('.daily-list li').count()>0);
  await f.locator('.activity-bar').nth(0).hover();
  assert.ok((await f.locator('.daily-heading').innerText()).includes(date),'Hover must not replace pinned ranking');
  await page.screenshot({animations:'disabled',path:path.join(output,'daily.png')});
  await f.getByRole('button',{name:t('返回全部','Back to all'),exact:true}).click();
  assert.equal(await f.locator('.activity-bar[aria-pressed=true]').count(),0);
  assert.equal(await f.locator('.entity-panel').isVisible(),true);
  checks.push('bar hover, click, cross-chart pin, daily named ranks and return to period');
  await f.getByRole('button',{name:'Skill',exact:true}).click();
  await f.locator('.activity-bar').last().click();
  assert.ok((await f.locator('.activity-tooltip').first().innerText()).includes(t('采用','adoption')));
  await f.getByRole('button',{name:t('返回全部','Back to all'),exact:true}).click();
  await f.getByRole('button',{name:t('插件','Plugins'),exact:true}).click();
  const firstBar=f.locator('.activity-bar').first();await firstBar.focus();await firstBar.press('ArrowRight');
  assert.equal(await f.locator('.activity-bar').nth(1).evaluate(e=>e===document.activeElement),true);
  await f.locator('.activity-bar').nth(1).press('Enter');
  assert.equal(await f.locator('.activity-bar[aria-pressed=true]').count(),1);
  assert.equal(await f.locator('.activity-bar[aria-pressed=true]').evaluate(e=>e===document.activeElement),true);
  await f.getByRole('button',{name:t('返回全部','Back to all'),exact:true}).click();
  checks.push('separate Skill metric and keyboard daily selection');
  // Reload clears incidental hover previews before the full overview capture.
  await page.reload();await f.locator('.activity-bar').last().waitFor();
  await page.screenshot({animations:'disabled',path:path.join(output,'activity.png')});
  await page.emulateMedia({colorScheme:'dark'});
  assert.equal((await f.locator('html').evaluate(e=>getComputedStyle(e).getPropertyValue('--heat-4'))).trim(),'#b0dbc7');
  await page.screenshot({animations:'disabled',path:path.join(output,'dark.png')});
  await page.emulateMedia({colorScheme:'light'});
  await page.getByRole('button',{name:t('窄面板','Narrow panel'),exact:true}).click();
  const sizes=await f.locator('body').evaluate(e=>({width:e.clientWidth,scroll:e.scrollWidth,calendar:document.querySelector('.calendar-scroll').scrollWidth}));
  assert.ok(sizes.scroll<=sizes.width+1,JSON.stringify(sizes));
  assert.ok(sizes.calendar>sizes.width,'Only the annual calendar should scroll horizontally');
  await page.screenshot({animations:'disabled',path:path.join(output,'narrow.png')});
  checks.push('light/dark palette and 360px panel without whole-page overflow');
  await f.getByRole('button',{name:t('管理','Manage'),exact:true}).click();
  await f.locator('.source-summary').waitFor();
  assert.ok(await f.getByRole('button',{name:english?/^Personal skills,/:/^个人技能，/}).count());
  checks.push('existing Manage/source navigation remains available');
  assert.deepEqual(errors,[]);
  const result={checks,errors,locale:english?'en':'zh',viewport:1100,narrowPanel:360,data:'Synthetic only',nativeDesktop:'not tested'};
  await writeFile(path.join(output,'checks.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
}finally{await browser.close();}
