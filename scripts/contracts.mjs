// Generates the language-neutral tool contracts consumed by the frontend:
//   contracts/schema/v<N>/tools/<tool>.input.json
//   contracts/schema/v<N>/outputs/<name>.json
//   contracts/schema/v<N>/index.json
//   src/frontend/generated/contracts.mjs   (the frontend's only view of the contracts)
// `node scripts/contracts.mjs --check` fails when committed files differ from a fresh generation.
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { z } from 'zod';
import { inputs, outputs, CONTRACT_VERSION } from '../src/backend/contracts/tools.mjs';
import { loadConfig } from '../src/backend/config/loader.mjs';
import { selectPlatform } from '../src/backend/adapters/platform/index.mjs';

const check = process.argv.includes('--check');
const config = loadConfig({ platform: selectPlatform(), env: {}, userFile: null });
const base = path.join('contracts', 'schema', `v${CONTRACT_VERSION}`);
const files = new Map();
const json = value => JSON.stringify(value, null, 2) + '\n';

const toolNames = Object.keys(inputs).sort();
for (const name of toolNames) files.set(path.join(base, 'tools', `${name}.input.json`), json(z.toJSONSchema(inputs[name](config), { io: 'input' })));
const outputModes = {};
for (const [name, schema] of Object.entries(outputs).sort(([a], [b]) => a.localeCompare(b))) {
  const generated = z.toJSONSchema(schema, { io: 'output', unrepresentable: 'any' });
  files.set(path.join(base, 'outputs', `${name}.json`), json(generated));
  outputModes[name] = generated.properties?.mode?.const ?? null;
}
files.set(path.join(base, 'index.json'), json({ version: CONTRACT_VERSION, tools: toolNames, outputs: outputModes }));
files.set(path.join('src', 'frontend', 'generated', 'contracts.mjs'),
  `// GENERATED by scripts/contracts.mjs from src/backend/contracts/tools.mjs — do not edit.\n` +
  `export const CONTRACT_VERSION = ${CONTRACT_VERSION};\n` +
  `export const TOOLS = Object.freeze(${JSON.stringify(Object.fromEntries(toolNames.map(n => [n, n])), null, 2)});\n` +
  `/** structuredContent.mode values per output contract. */\n` +
  `export const OUTPUT_MODES = Object.freeze(${JSON.stringify(outputModes, null, 2)});\n`);

if (check) {
  const stale = [];
  // Line endings are not part of the contract (Windows checkouts may use CRLF).
  const normalize = value => value?.replace(/\r\n/g, '\n');
  for (const [file, text] of files) if (normalize(await readFile(file, 'utf8').catch(() => null)) !== text) stale.push(file);
  if (stale.length) { console.error(`Contracts are stale; run \`pnpm run contracts\`:\n  ${stale.join('\n  ')}`); process.exit(1); }
  console.log(`Contracts v${CONTRACT_VERSION} are up to date (${files.size} files).`);
} else {
  await rm(base, { recursive: true, force: true });
  for (const [file, text] of files) { await mkdir(path.dirname(file), { recursive: true }); await writeFile(file, text); }
  console.log(`Wrote contracts v${CONTRACT_VERSION} (${files.size} files).`);
}
